// MCPB BUNDLE DRIFT GUARD.
//
//   npm run verify:mcpb            # warn (default)
//   npm run verify:mcpb -- --strict  # exit 1 on drift
//
// ── The hazard, stated generally ─────────────────────────────────────────
// mcpb/server/index.js is a COMMITTED BUILD ARTIFACT: an esbuild bundle of
// src/stdio-server.ts, regenerated only when someone runs `npm run build:mcpb`.
// Every other published surface in this repo is either generated with a
// --check drift guard (toolspec, openapi, well-known) or read live from source.
// This one is neither. Nothing in `npm test` or `npm run typecheck` reads it,
// so source and bundle can diverge arbitrarily far without a single failure -
// and the bundle is what Claude Desktop actually executes. A release that
// skips build:mcpb ships the PREVIOUS release's server to every Desktop
// install while every other surface gets the new one.
//
// ── The instance that motivated this check ───────────────────────────────
// The committed bundle still embeds `lib/data/trailing-vols.json`, the baked
// implied-vol table deleted in 2026-08. That table was stamped 2026-06-05.
// Its deletion was the entire point of moving volatility onto a published feed
// behind a last-close freshness gate: the bundle hands back June sigmas, with
// no gate, as confident facts. Marker-based rather than hash-based on purpose -
// a hash guard fails on every unrelated source edit and gets muted; a marker
// for a module that no longer exists cannot false-positive.
//
// ── Why this defaults to WARN and not FAIL ───────────────────────────────
// The fix is to regenerate the bundle, which is a ~1MB machine-generated diff,
// AND to repack optionsahoy.mcpb via `npx @anthropic-ai/mcpb pack` - a network
// fetch of a floating @latest producing a zip whose bytes are not reproducible.
// Regenerating index.js WITHOUT repacking the .mcpb would replace one drift
// with a worse one (bundle and packed extension disagreeing). So the guard
// reports loudly and the fix belongs to the release that runs build:mcpb for
// real. Flip the default to strict once the bundle has been regenerated by such
// a release - see the PR that added this file.

import { readFileSync } from 'node:fs';

const BUNDLE = 'mcpb/server/index.js';
const strict = process.argv.includes('--strict');

// Markers for modules that NO LONGER EXIST in source. Presence in the bundle
// is proof it predates their deletion; absence proves nothing on its own, which
// is why each entry names the change it postdates.
const DELETED_MODULE_MARKERS = [
  { marker: 'trailing-vols', since: 'volatility moved to the published feed (2026-08); the baked table was stamped 2026-06-05' },
];

let bundle;
try {
  bundle = readFileSync(BUNDLE, 'utf8');
} catch (err) {
  if (err.code === 'ENOENT') {
    console.log(`verify:mcpb  skip (absent): ${BUNDLE} - run \`npm run build:mcpb\` to create it`);
    process.exit(0);
  }
  throw err;
}

const hits = DELETED_MODULE_MARKERS.filter(({ marker }) => bundle.includes(marker));

if (hits.length === 0) {
  console.log(`verify:mcpb  ok: ${BUNDLE} carries no deleted-module markers`);
  process.exit(0);
}

const lines = [
  '',
  `verify:mcpb  ${strict ? 'FAILED' : 'WARNING'}: ${BUNDLE} is a STALE BUILD ARTIFACT.`,
  '',
  ...hits.map(({ marker, since }) => `  references "${marker}", removed from source when ${since}`),
  '',
  '  This bundle is what the Claude Desktop extension executes. Until it is',
  '  regenerated it serves the OLD behaviour to every Desktop install while the',
  '  hosted and npm surfaces serve the new one.',
  '',
  '  Fix: npm run build:mcpb   (rebuilds dist/, copies it here, repacks optionsahoy.mcpb)',
  '',
];
console.error(lines.join('\n'));
process.exit(strict ? 1 : 0);
